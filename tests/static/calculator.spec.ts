test('individual assignments mix points and percentages, with weight validation and custom rows', async ({ page }) => {
  await page.goto('/calc')
  const midterm = page.getByRole('region', { name: 'Midterm', exact: true })
  await midterm.getByRole('button', { name: 'По заданиям и разделам' }).click()
  const assignment = (number: number) =>
    midterm.getByRole('group', { name: `Midterm, Assignment ${number} (week ${number})`, exact: true })
  await assignment(1).getByLabel('Оценка (баллы)', { exact: true }).fill('12')
  await assignment(1).getByLabel('Формат оценки').selectOption('percent')
  await expect(assignment(1).getByLabel('Оценка (%)', { exact: true })).toHaveValue('80')
  await assignment(1).getByLabel('Формат оценки').selectOption('points')
  await expect(assignment(1).getByLabel('Оценка (баллы)', { exact: true })).toHaveValue('12')
  for (const number of [2, 3, 4]) await assignment(number).getByLabel('Оценка (баллы)', { exact: true }).fill('15')
  const exam = midterm.getByRole('group', { name: 'Midterm, Midterm exam', exact: true })
  await exam.getByLabel('Формат оценки').selectOption('percent')
  await exam.getByLabel('Оценка (%)', { exact: true }).fill('75')
  await expect(midterm.getByText('Итог Midterm: 87 / 100', { exact: true })).toBeVisible()
  await expect(midterm.getByText('Вклад в курс: 26.1 / 30', { exact: true })).toBeVisible()

  await midterm.getByRole('button', { name: 'Добавить задание / раздел' }).click()
  const custom = midterm.getByRole('group', { name: 'Midterm, Новое задание 6', exact: true })
  await custom.getByLabel('Название', { exact: true }).fill('Project')
  const project = midterm.getByRole('group', { name: 'Midterm, Project', exact: true })
  await project.getByLabel('Вес (%)', { exact: true }).fill('10')
  await project.getByLabel('Максимум баллов').fill('20')
  await project.getByLabel('Оценка (баллы)', { exact: true }).fill('10')
  await expect(midterm.getByRole('alert')).toContainText('Сумма весов: 110%')
  await expect(page.locator('.calc-result')).toHaveCount(0)
  await exam.getByLabel('Вес (%)', { exact: true }).fill('30')
  await expect(midterm.getByRole('alert')).toHaveCount(0)
  await expect(midterm.getByText('Итог Midterm: 84.5 / 100', { exact: true })).toBeVisible()
  await project.getByRole('button', { name: 'Удалить Project' }).click()
  await exam.getByLabel('Вес (%)', { exact: true }).fill('40')
  await expect(midterm.getByText('Итог Midterm: 87 / 100', { exact: true })).toBeVisible()
})

